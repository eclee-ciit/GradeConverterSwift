    private void ComputeButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_ComputeButtonActionPerformed
        // TODO add your handling code here:
        int atf = Integer.parseInt(AssignmentTextField.getText());
        int qtf = Integer.parseInt(QuizTextField.getText());
        int etf = Integer.parseInt(ExamTextField.getText());
        
        double mark;
        
        mark = (atf * .25) + (qtf * .25) + (etf * .5);
        
        int markf = (int) mark;
        
        MarkNumberLabel.setText(String.valueOf(markf));
        
        if (markf < 75) {
            GradeNumberLabel.setText("0.00");
        } else if (markf >= 75 && markf <= 82) {
            GradeNumberLabel.setText("1.00");
        } else if (markf >= 83 && markf <= 88) {
            GradeNumberLabel.setText("2.00");
        } else if (markf >= 89 && markf <= 94) {
            GradeNumberLabel.setText("3.00");
        } else if (markf >= 95 && markf <= 100) {
            GradeNumberLabel.setText("4.00");
        } else {
            JOptionPane.showMessageDialog(
                null, 
                "Error: Invalid score", 
                "Calculation Error", 
                JOptionPane.ERROR_MESSAGE
            );
        }
    }//GEN-LAST:event_ComputeButtonActionPerformed

